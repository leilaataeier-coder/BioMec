import numpy

def среднее(числа):
    return sum(числа) / len(числа)

измерения = [35, 38, 36, 37, 39]
центр = среднее(измерения)
дисперсия = sum((число-центр)**2 for число in измерения) / 4
сигма = дисперсия**0.5
генератор = numpy.random.default_rng(2024)
группы = [измерения]
for номер in range(5):
    сдвиг = генератор.normal(0, 2)
    шум = генератор.normal(0, сигма)
    группы.append([round(центр + сдвиг + шум, 2)])

количество = sum(len(ряд) for ряд in группы)
практики = len(группы)
общая = sum(sum(ряд) for ряд in группы) / количество
внутри = sum(sum((значение-среднее(ряд))**2 for значение in ряд) for ряд in группы)
между = sum(len(ряд)*(среднее(ряд)-общая)**2 for ряд in группы)
средний_внутри = внутри / (количество-практики)
средний_между = между / (практики-1)
поправка = (количество - sum(len(ряд)**2 for ряд in группы)/количество)/(практики-1)
оценка = max(0, (средний_между - средний_внутри)/поправка)**0.5

print('реальные измерения:', измерения)
print('среднее:', round(центр, 2))
print('дисперсия:', round(дисперсия, 2))
print('стандартное отклонение:', round(сигма, 3))
print('коэффициент вариации:', round(100*сигма/центр, 2), '%')
print('группы:', [(f'П{номер}', значения) for номер, значения in enumerate(группы, 1)])
print('средние квадраты:', round(средний_внутри, 4), round(средний_между, 4))
print('между практиками:', round(оценка, 3))
